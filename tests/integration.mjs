import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const env = Object.fromEntries(readFileSync(new URL('../.env', import.meta.url), 'utf8').trim().split(/\r?\n/).filter(x=>x.includes('=')).map(x=>{const n=x.indexOf('=');return [x.slice(0,n),x.slice(n+1)];}));
const base = process.env.TEST_URL || 'http://localhost:5180';
let cookie='';
const instances=new Map();
async function request(path, method='GET', body, token) {
  if(token&&!instances.has(token))instances.set(token,crypto.randomUUID());
  const response=await fetch(base+'/api'+path,{method,headers:{'Content-Type':'application/json','X-Requested-With':'BackupControl',...(token?{Authorization:`Bearer ${token}`,'X-Agent-Instance':instances.get(token)}:{Cookie:cookie})},body:body===undefined?undefined:JSON.stringify(body)});
  if(response.headers.get('set-cookie')) cookie=response.headers.get('set-cookie').split(';')[0];
  const text=await response.text(); let data;try{data=JSON.parse(text);}catch{data=text;}
  return {status:response.status,data};
}
test('Fluxo real: autenticação, cliente, isolamento, fila e resultado idempotente',async(t)=>{
  assert.equal((await request('/clients')).status,401);
  assert.equal((await request('/auth/login','POST',{username:env.ADMIN_USER,password:'incorrect'})).status,401);
  assert.equal((await request('/auth/login','POST',{username:env.ADMIN_USER,password:env.ADMIN_PASSWORD})).status,200);
  assert.equal((await fetch(base+'/api/clients',{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json'},body:'{}'})).status,403);
  const config=await request('/storage');
  assert.equal(config.status,200);
  assert.equal('password' in config.data,false);
  assert.equal((await request('/clients','POST',{name:'Inválido',slug:'../escape',database:'Banco'})).status,400);
  const slug='teste-'+Date.now();
  assert.equal((await request('/clients','POST',{name:'Agenda inválida',slug:'invalid-'+Date.now(),database:'Banco',expectedIntervalHours:4,differentialIntervalHours:4})).status,400);
  const client=await request('/clients','POST',{name:'Teste automatizado',slug,database:'BancoTeste',expectedIntervalHours:24,graceMinutes:60,differentialIntervalHours:4});
  assert.equal(client.status,201);
  const id=client.data.id,token=client.data.agentToken;
  t.after(async()=>{await request(`/clients/${id}`,'DELETE');});
  assert.ok(token?.length>20);
  assert.equal((await request('/clients','POST',{name:'Duplicado',slug,database:'BancoTeste'})).status,409);
  const listing=await request('/clients');
  assert.ok(listing.data.some(c=>c.id===id));
  assert.equal('agentToken' in listing.data.find(c=>c.id===id),false);
  assert.equal((await request('/agent/config','GET',undefined,'invalid')).status,401);
  const agentConfig=await request('/agent/config','GET',undefined,token);
  assert.equal(agentConfig.data.remoteDirectory,`/backup/${slug}`);
  assert.equal(agentConfig.data.differentialIntervalHours,4);
  const telemetry={nextFullAt:new Date(Date.now()+86400000).toISOString(),nextDifferentialAt:new Date(Date.now()+14400000).toISOString(),lastSuccessfulFullAt:new Date().toISOString(),hasFullBase:true,scheduleEnabled:true,appliedFullIntervalHours:24,appliedDifferentialIntervalHours:4,appliedDatabase:'BancoTeste',configAppliedAt:new Date().toISOString(),currentBackupType:null,currentPhase:null,currentStartedAt:null};
  assert.equal((await request('/agent/heartbeat','POST',{machineName:'Teste-Agenda',agentVersion:'0.3.0',telemetry},token)).status,200);
  const scheduled=(await request('/clients')).data.find(c=>c.id===id);
  assert.equal(Date.parse(scheduled.agentTelemetry.nextFullAt),Date.parse(telemetry.nextFullAt));
  assert.equal(Date.parse(scheduled.agentTelemetry.nextDifferentialAt),Date.parse(telemetry.nextDifferentialAt));
  assert.ok(scheduled.telemetryReceivedAt);
  const runningTelemetry={...telemetry,currentOrigin:'Manual',currentBackupType:'Full',currentPhase:'SqlStarted',currentStartedAt:new Date().toISOString()};
  assert.equal((await request('/agent/heartbeat','POST',{machineName:'Teste-Agenda',telemetry:runningTelemetry},token)).status,200);
  assert.equal((await request('/clients')).data.find(c=>c.id===id).agentTelemetry.currentOrigin,'Manual');
  assert.equal((await request('/agent/heartbeat','POST',{machineName:'Teste-Agenda',telemetry:{...runningTelemetry,currentOrigin:'Invalid'}},token)).status,400);
  assert.equal((await request('/agent/heartbeat','POST',{machineName:'Teste-Agenda',telemetry},token)).status,200);
  assert.equal((await request('/agent/heartbeat','POST',{machineName:'Teste-Agenda',telemetry:{...telemetry,currentPhase:'Invalid'}},token)).status,400);
  assert.equal((await request('/agent/heartbeat','POST',{machineName:'Teste-Agenda'},token)).status,200);
  assert.equal(Date.parse((await request('/clients')).data.find(c=>c.id===id).agentTelemetry.nextFullAt),Date.parse(telemetry.nextFullAt));
  assert.equal((await fetch(base+'/api/agent/config',{headers:{Authorization:`Bearer ${token}`,'X-Agent-Instance':crypto.randomUUID()}})).status,409);
  const command=await request(`/clients/${id}/commands`,'POST',{backupType:'Full'});
  assert.equal(command.status,201);
  assert.equal((await request(`/clients/${id}/commands`,'POST',{backupType:'Full'})).status,409);
  const claims=await Promise.all([request('/agent/commands/claim','POST',{},token),request('/agent/commands/claim','POST',{},token)]);
  assert.equal(claims.filter(r=>r.status===200).length,1);
  assert.equal(claims.filter(r=>r.status===204).length,1);
  const recovered=await request('/agent/commands/active','GET',undefined,token);
  assert.equal(recovered.status,200);
  assert.equal(recovered.data.id,command.data.id);
  const other=await request('/clients','POST',{name:'Teste isolamento',slug:slug+'b',database:'OutroBanco'});
  assert.equal(other.status,201);
  t.after(async()=>{await request(`/clients/${other.data.id}`,'DELETE');});
  const result={commandId:command.data.id,eventId:crypto.randomUUID(),backupType:'Full',status:'Succeeded',startedAt:new Date(Date.now()-1000).toISOString(),finishedAt:new Date().toISOString(),sizeBytes:1024,fileName:'BancoTeste_2026-11-13_full.zip',message:'Integração validada; não é um backup real.'};
  assert.equal((await request('/agent/results','POST',result,other.data.agentToken)).status,404);
  assert.equal((await request('/agent/results','POST',{...result,fileName:'../fora.zip'},token)).status,400);
  assert.equal((await request('/agent/results','POST',{...result,backupType:'Differential'},token)).status,400);
  assert.equal((await request('/agent/heartbeat','POST',{machineName:null},token)).status,400);
  assert.equal((await request('/agent/results','POST',result,token)).status,201);
  assert.equal((await request('/agent/commands/active','GET',undefined,token)).status,204);
  assert.equal((await request('/agent/results','POST',result,token)).status,200);
  assert.equal((await request('/agent/results','POST',{...result,eventId:crypto.randomUUID(),status:'Failed'},token)).status,409);
  const history=await request(`/runs?clientId=${id}`);
  assert.equal(history.data.length,1);
  assert.equal(history.data[0].status,'Succeeded');
  assert.equal(history.data[0].fileName,result.fileName);
  const pending=await request(`/clients/${id}/commands`,'POST',{backupType:'Full'});
  assert.equal(pending.status,201);
  assert.equal((await request(`/commands/${pending.data.id}/cancel`,'POST',{})).status,204);
  assert.equal((await request('/agent/commands/claim','POST',{},token)).status,204);
  const queuedBeforePause=await request(`/clients/${id}/commands`,'POST',{backupType:'Full'});
  assert.equal(queuedBeforePause.status,201);
  assert.equal((await request(`/clients/${id}/status`,'PATCH',{enabled:false})).status,200);
  const paused=(await request('/clients')).data.find(c=>c.id===id);
  assert.equal(paused.enabled,false);
  assert.equal(paused.hasActiveCommand,false);
  assert.equal((await request('/agent/config','GET',undefined,token)).status,401);
  assert.equal((await request(`/clients/${id}/commands`,'POST',{backupType:'Full'})).status,400);
  assert.equal((await request(`/runs?clientId=${id}`)).data.length,1);
  assert.equal((await request(`/clients/${id}/status`,'PATCH',{enabled:true})).status,200);
  assert.equal((await request('/agent/config','GET',undefined,token)).status,200);
  assert.equal((await request('/agent/commands/claim','POST',{},token)).status,204);
  assert.equal((await request(`/clients/${id}`,'DELETE')).status,204);
  assert.equal((await request('/agent/config','GET',undefined,token)).status,401);
});

