import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, createWriteStream } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { Readable, Transform } from 'node:stream';
import { pipeline } from 'node:stream/promises';

const env=Object.fromEntries(readFileSync(new URL('../.env',import.meta.url),'utf8').split(/\r?\n/).filter(x=>x.includes('=')).map(x=>{const n=x.indexOf('=');return [x.slice(0,n),x.slice(n+1)];}));
const base=(process.env.TEST_URL||'http://localhost:5180')+'/api';
let cookie='';
const get=path=>fetch(base+path,{headers:{Cookie:cookie}});

test('Catálogo real: autenticação, isolamento por cadastro e download sem modificar o FTP',async()=>{
  const anonymous=await fetch(base+'/clients/00000000-0000-0000-0000-000000000001/files');
  assert.equal(anonymous.status,401);
  const login=await fetch(base+'/auth/login',{method:'POST',headers:{'Content-Type':'application/json','X-Requested-With':'BackupControl'},body:JSON.stringify({username:env.ADMIN_USER||'admin',password:env.ADMIN_PASSWORD})});
  assert.equal(login.status,200);
  cookie=login.headers.get('set-cookie').split(';')[0];
  const clients=await (await get('/clients')).json();
  assert.ok(clients.length,'É necessário um cliente cadastrado com arquivos reais para este teste.');
  const client=clients.find(c=>c.slug==='cliente-local')||clients[0];
  assert.equal((await get('/clients/00000000-0000-0000-0000-000000000001/files')).status,404);
  assert.equal((await get(`/clients/${client.id}/files/download?fileName=${encodeURIComponent('../other/file.zip')}`)).status,400);
  assert.equal((await get(`/clients/${client.id}/files/download?fileName=test.zip.uploading`)).status,400);
  const listing=await get(`/clients/${client.id}/files`);
  assert.equal(listing.status,200,await listing.clone().text());
  const catalog=await listing.json();
  assert.equal(catalog.clientId,client.id);
  assert.ok(catalog.remoteDirectory.endsWith('/'+client.slug));
  assert.equal(JSON.stringify(catalog).includes('password'),false);
  assert.equal((await get(`/clients/${client.id}/files/download?fileName=missing-${crypto.randomUUID()}.zip`)).status,404);
  const file=catalog.files.filter(f=>f.status==='Available'&&f.sizeBytes>0).sort((a,b)=>a.sizeBytes-b.sizeBytes)[0];
  assert.ok(file,'Nenhum backup disponível para download.');
  assert.ok(file.backupType);
  const response=await get(`/clients/${client.id}/files/download?fileName=${encodeURIComponent(file.fileName)}`);
  assert.equal(response.status,200);
  assert.equal(response.headers.get('content-type'),'application/zip');
  assert.match(response.headers.get('content-disposition'),/attachment/);
  const folder=fileURLToPath(new URL('../../../work/catalog-validation/',import.meta.url));
  mkdirSync(folder,{recursive:true});
  const hash=createHash('sha256');let size=0;
  await pipeline(Readable.fromWeb(response.body),new Transform({transform(chunk,encoding,done){size+=chunk.length;hash.update(chunk);done(null,chunk);}}),createWriteStream(resolve(folder,file.fileName)));
  assert.equal(size,file.sizeBytes);
  const sha256=hash.digest('hex');
  const runs=await (await get(`/runs?clientId=${client.id}`)).json();
  const run=runs.find(r=>r.fileName===file.fileName&&r.status==='Succeeded');
  const expected=run?.message.match(/[a-f0-9]{64}$/)?.[0];
  if(expected)assert.equal(sha256,expected);
  console.log(JSON.stringify({client:client.name,files:catalog.files.length,download:file.fileName,size,sha256,comparedToAgent:!!expected},null,2));
});
